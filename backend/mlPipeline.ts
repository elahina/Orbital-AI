export function calculateSubIndex(conc: number, breakpoints: SubIndexBreakpoint[]): number {
  if (conc <= 0) return 0;
  for (const bp of breakpoints) {
    if (conc <= bp.cHigh) {
      return Math.round(
        bp.iLow + ((bp.iHigh - bp.iLow) / (bp.cHigh - bp.cLow)) * (conc - bp.cLow)
      );
    }
  }
  return 500;
}

export function computeAqi(
  pm25: number,
  pm10: number,
  no2: number,
  co: number,
  ozone: number,
  so2 = 12.0
): PollutantMeasurement {
  const iPm25 = calculateSubIndex(pm25, PM25_BREAKPOINTS);
  const iPm10 = calculateSubIndex(pm10, PM10_BREAKPOINTS);
  const iNo2 = calculateSubIndex(no2, NO2_BREAKPOINTS);
  const iCo = calculateSubIndex(co, CO_BREAKPOINTS);
  const iO3 = calculateSubIndex(ozone, O3_BREAKPOINTS);

  const subIndices = [
    { name: 'PM2.5', val: iPm25 },
    { name: 'PM10', val: iPm10 },
    { name: 'NO2', val: iNo2 },
    { name: 'CO', val: iCo },
    { name: 'Ozone', val: iO3 },
  ];

  subIndices.sort((a, b) => b.val - a.val);
  const prominent = subIndices[0].name;
  const aqi = Math.max(iPm25, iPm10, iNo2, iCo, iO3);

  let category: PollutantMeasurement['category'] = 'Good';
  let categoryColor = '#39ff14'; // neon green

  if (aqi <= 50) {
    category = 'Good';
    categoryColor = '#39ff14';
  } else if (aqi <= 100) {
    category = 'Satisfactory';
    categoryColor = '#84cc16';
  } else if (aqi <= 200) {
    category = 'Moderate';
    categoryColor = '#eab308';
  } else if (aqi <= 300) {
    category = 'Poor';
    categoryColor = '#f97316';
  } else if (aqi <= 400) {
    category = 'Very Poor';
    categoryColor = '#ef4444';
  } else {
    category = 'Severe';
    categoryColor = '#9333ea';
  }

  return {
    aqi,
    pm25,
    no2,
    co,
    ozone,
    pm10,
    so2,
    category,
    categoryColor,
    prominentPollutant: prominent,
  };
}

